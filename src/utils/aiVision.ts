import type { PhotoDetectionSuggestion, RoomModel } from '../types/model';

/**
 * AI & Vision Service
 * 
 * Privacy & Technical Principles:
 * 1. Zero external calls without explicit user consent.
 * 2. On-device local analysis by default (100% offline & private).
 * 3. Photo-derived measurements are tagged as estimates ('photo-estimate'), NEVER ground truth.
 * 4. Graceful degradation when external models are unavailable.
 * 5. Full disclosure of heuristic & model fallbacks.
 */

export interface AnalysisOptions {
  consentExternalAi: boolean;
  apiKey?: string;
  room: RoomModel;
}

export interface AnalysisResult {
  source: 'local-heuristic-engine' | 'gemini-vision-api' | 'fallback';
  suggestions: PhotoDetectionSuggestion[];
  disclaimer: string;
  modelLicense: string;
}

/**
 * Perform room photo analysis to suggest furniture objects and estimated dimensions
 */
export async function analyzeRoomPhoto(
  imageDataUrl: string, 
  options: AnalysisOptions
): Promise<AnalysisResult> {
  const { consentExternalAi, apiKey, room } = options;

  // If user consented to external AI and provided a valid API key, attempt Gemini Vision API
  if (consentExternalAi && apiKey && apiKey.trim().length > 10) {
    try {
      const geminiResult = await callGeminiVision(imageDataUrl, apiKey, room);
      if (geminiResult && geminiResult.length > 0) {
        return {
          source: 'gemini-vision-api',
          suggestions: geminiResult,
          disclaimer: 'Estimated by Gemini 1.5 Flash Vision. All dimensions are approximations and must be physically measured before purchase.',
          modelLicense: 'Google Gemini API Terms of Service (Commercial & Personal Use)',
        };
      }
    } catch (err) {
      console.warn('External AI vision failed or rate limited; gracefully falling back to local engine.', err);
    }
  }

  // Local On-Device Heuristic Engine (100% Private, Offline-first)
  const localSuggestions = analyzePhotoLocally(imageDataUrl, room);

  return {
    source: 'local-heuristic-engine',
    suggestions: localSuggestions,
    disclaimer: 'Generated by FitCheck on-device room analysis engine (100% private, no image data left your device). All dimensions are estimates.',
    modelLicense: 'FitCheck Built-in Heuristic Spatial Engine (MIT License)',
  };
}

